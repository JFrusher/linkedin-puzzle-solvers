"""Shared NLP resources: the Sentence-BERT encoder and the WordNet lexicon."""

from __future__ import annotations

from functools import lru_cache
from typing import TYPE_CHECKING

import numpy as np

if TYPE_CHECKING:
    from nltk.corpus.reader.wordnet import WordNetCorpusReader
    from sentence_transformers import SentenceTransformer

MODEL_NAME = "all-MiniLM-L6-v2"


@lru_cache(maxsize=1)
def encoder() -> SentenceTransformer:
    """Load the Sentence-BERT model once per process."""
    from sentence_transformers import SentenceTransformer

    return SentenceTransformer(MODEL_NAME, device="cpu")


def embed(texts: list[str]) -> np.ndarray:
    """Return L2-normalised embeddings (rows), so dot products are cosine similarities."""
    if not texts:
        raise ValueError("embed() needs at least one text")
    return np.asarray(encoder().encode(texts, normalize_embeddings=True, show_progress_bar=False), dtype=np.float32)


@lru_cache(maxsize=1)
def wordnet() -> WordNetCorpusReader:
    """Return the WordNet corpus, failing fast with the install command if it is missing."""
    from nltk.corpus import wordnet as wn

    try:
        wn.ensure_loaded()
    except LookupError as error:
        raise RuntimeError("WordNet corpus missing: run `python -m nltk.downloader wordnet`") from error
    return wn


@lru_cache(maxsize=4)
def dictionary_words(min_length: int = 3) -> frozenset[str]:
    """All single-word, purely alphabetic WordNet lemmas, upper-cased."""
    return frozenset(
        name.upper()
        for name in wordnet().all_lemma_names()
        if name.isalpha() and name.isascii() and len(name) >= min_length
    )


_VOWELS = set("aeiou")


def _syllables(word: str) -> int:
    """Vowel groups, ignoring a silent final 'e': a close enough syllable count for inflection rules."""
    word = word[:-1] if word.endswith("e") and not word.endswith(("ee", "le")) else word
    return sum(1 for i, ch in enumerate(word) if ch in _VOWELS and (i == 0 or word[i - 1] not in _VOWELS))


def _double_final(word: str) -> bool:
    """Short consonant-vowel-consonant words double their last letter: stop -> stopped, big -> bigger."""
    return (
        _syllables(word) == 1
        and len(word) >= 3
        and word[-1] not in _VOWELS | set("wxy")
        and word[-2] in _VOWELS
        and word[-3] not in _VOWELS
    )


def _inflections(word: str, pos: str) -> set[str]:
    """Regular English inflections of ``word`` for its part of speech ('n', 'v', 'a')."""
    consonant_y = word.endswith("y") and len(word) > 1 and word[-2] not in _VOWELS
    if word.endswith(("s", "x", "z", "ch", "sh")):
        plural = word + "es"
    else:
        plural = word[:-1] + "ies" if consonant_y else word + "s"
    if pos == "n":
        return {plural}
    stem = word + word[-1] if _double_final(word) else word[:-1] + "i" if consonant_y else word
    if pos == "v":
        past = word + "d" if word.endswith("e") else stem + "ed"
        gerund = word[:-1] + "ing" if word.endswith("e") and not word.endswith(("ee", "ye", "oe")) else stem + "ing"
        return {plural, past, gerund} if not consonant_y else {plural, past, word + "ing"}
    if _syllables(word) != 1 and not (consonant_y or word.endswith("le")):
        return set()  # longer adjectives take "more" and "most": no "comparablest", but "happier", "simpler"
    base = word[:-1] if word.endswith("e") else stem
    return {base + "er", base + "est"}


def _irregular_forms(wn: WordNetCorpusReader, pos: str) -> list[str]:
    """WordNet's irregular forms (GEESE, RAN); NLTK keeps them in a private map, so fail clearly if it moves."""
    exceptions = getattr(wn, "_exception_map", None)
    if exceptions is None:
        raise RuntimeError("this NLTK version no longer exposes WordNet's exception lists (_exception_map)")
    return list(exceptions[pos])


@lru_cache(maxsize=4)
def word_forms(min_length: int = 3) -> frozenset[str]:
    """Dictionary words plus their inflections (DOWNLOADED, GEESE), upper-cased.

    Regular forms are generated by spelling rules and kept only when WordNet maps them back to their lemma;
    irregular forms come from WordNet's exception lists.
    """
    wn = wordnet()
    forms = set(dictionary_words(min_length))
    for pos in ("n", "v", "a"):
        for synset in wn.all_synsets(pos):
            for lemma in synset.lemma_names():
                if lemma.isalpha() and lemma.isascii():
                    forms |= {f.upper() for f in _inflections(lemma, pos) if wn.morphy(f, pos) == lemma}
        forms |= {f.upper() for f in _irregular_forms(wn, pos) if f.isalpha() and f.isascii()}
    return frozenset(form for form in forms if len(form) >= min_length)
